// Run against a fresh production preview (npm run build; npm run preview).
async (page) => {
  const browser = page.context().browser()
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 } })
  const assert = (value, message) => { if (!value) throw new Error(message) }
  const results = { transitions: [], mobile: [], errors: [] }
  try {
    await context.addInitScript(() => {
      const Native = window.AudioContext
      window.__phaseContexts = []
      window.AudioContext = class extends Native { constructor(...args) { super(...args); window.__phaseContexts.push(this) } }
      window.__phaseHidden = false
      Object.defineProperty(document, 'hidden', { configurable: true, get: () => window.__phaseHidden })
    })
    const test = await context.newPage()
    test.on('pageerror', error => results.errors.push(error.message))
    await test.goto('http://127.0.0.1:4173/?inspect=1')
    const debug = test.locator('[data-audio-debug]')
    const snapshot = () => debug.evaluate(element => ({ ...element.dataset, energy: JSON.parse(element.dataset.energy) }))
    const waitState = state => test.waitForFunction(state => document.querySelector('[data-audio-debug]').dataset.state === state, state)
    const audible = () => test.waitForFunction(() => JSON.parse(document.querySelector('[data-audio-debug]').dataset.energy).rms > 0.0001)
    const released = () => test.waitForFunction(() => document.querySelector('[data-audio-debug]').dataset.voices === '0')
    assert((await snapshot()).contexts === '0', 'Autoplay/context on load')
    await test.getByRole('button', { name: 'View ECHO study', exact: true }).click()
    await test.getByRole('tab', { name: 'AFTERIMAGE', exact: true }).click()
    await test.keyboard.press('Escape')
    assert((await snapshot()).contexts === '0', 'Visual selection created audio')
    await test.getByRole('button', { name: 'Enable sound', exact: true }).click()
    await waitState('ready')
    assert((await snapshot()).voices === '0' && (await snapshot()).contexts === '1', 'Enable played sound')
    results.transitions.push('off → ready, no voice')
    await test.getByRole('button', { name: 'Play FORM study', exact: true }).click()
    await waitState('playing'); await audible()
    assert((await snapshot()).active === 'form', 'FORM inactive')
    assert(await test.locator('.study-form svg.study-visual').getAttribute('data-audio-reactive') === 'true', 'FORM not reactive')
    const volume = test.getByRole('slider', { name: 'Playback volume' })
    await volume.focus(); await test.keyboard.press('Home')
    await test.waitForFunction(() => { const e = JSON.parse(document.querySelector('[data-audio-debug]').dataset.energy); return e.elapsed > .5 && e.rms === 0 && e.bass === 0 && e.mid === 0 && e.high === 0 })
    assert((await snapshot()).volume === '0', 'Volume keyboard mute')
    await test.keyboard.press('End'); await audible()
    assert((await snapshot()).volume === '1', 'Volume keyboard maximum')
    await test.getByRole('button', { name: 'Play ECHO study', exact: true }).click()
    await waitState('playing'); await audible()
    assert((await snapshot()).active === 'echo' && (await snapshot()).maxVoices === '1', 'Switch overlap')
    results.transitions.push('FORM → mute → volume → ECHO, one voice')
    await test.getByRole('button', { name: 'Stop playback', exact: true }).click()
    await released()
    assert((await snapshot()).energy.level === 0 && (await snapshot()).nodes === '4', 'Stop leaves audio resources')
    await test.getByRole('button', { name: 'View AFTERIMAGE study', exact: true }).click()
    await test.getByRole('dialog').getByRole('button', { name: 'Play AFTERIMAGE study', exact: true }).click()
    await waitState('playing'); await audible()
    assert(await test.locator('.study-panel:not([hidden]) svg').getAttribute('data-audio-reactive') === 'true', 'Panel not reactive')
    assert(await test.getByRole('button', { name: 'Replay motion' }).isDisabled(), 'Visual replay competes with audio time')
    await test.getByRole('tab', { name: 'FORM', exact: true }).click()
    await released()
    assert((await snapshot()).state === 'stopped' && (await snapshot()).reason === 'selection', 'Tab selection starts/keeps old audio')
    await test.getByRole('dialog').getByRole('button', { name: 'Play FORM study', exact: true }).click()
    await waitState('playing')
    await test.keyboard.press('Escape')
    assert(await test.getByRole('button', { name: 'Stop playback', exact: true }).isVisible(), 'No Stop after dialog close')
    await test.evaluate(() => { window.__phaseHidden = true; document.dispatchEvent(new Event('visibilitychange')) })
    await released()
    assert((await snapshot()).reason === 'hidden', 'Hidden audio not stopped')
    await test.evaluate(() => { window.__phaseHidden = false; document.dispatchEvent(new Event('visibilitychange')) })
    assert((await snapshot()).state === 'stopped' && await test.evaluate(() => window.__phaseContexts[0].state) === 'suspended', 'Auto resumed on return')
    await test.getByRole('button', { name: 'Play again', exact: true }).click()
    await waitState('playing')
    assert((await snapshot()).contexts === '1', 'Return creates another context')
    results.transitions.push('dialog selection stops, Escape keeps Stop accessible, hidden stops, return stays silent')
    await test.evaluate(() => window.__phaseContexts[0].suspend())
    await released()
    assert((await snapshot()).reason === 'interrupted', 'System interruption ignored')
    await test.getByRole('button', { name: 'Play again', exact: true }).click(); await waitState('playing')
    await test.evaluate(() => window.dispatchEvent(new PageTransitionEvent('pagehide', { persisted: true })))
    await released()
    await test.evaluate(() => window.dispatchEvent(new PageTransitionEvent('pageshow', { persisted: true })))
    assert((await snapshot()).state === 'stopped', 'BFCache auto resumed')
    await test.getByRole('button', { name: 'Play again', exact: true }).click(); await waitState('playing')
    for (const width of [1440, 390, 320]) {
      await test.setViewportSize({ width, height: width === 320 ? 568 : width === 390 ? 844 : 900 })
      await test.evaluate(() => scrollTo({ top: 0, behavior: 'instant' }))
      assert(await test.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth), `Player page overflow ${width}`)
      await test.screenshot({ path: `artifacts/qa/phase4-player-${width}.png` })
      await test.getByRole('button', { name: 'View ECHO study', exact: true }).click()
      const dialog = test.getByRole('dialog')
      const bounds = await dialog.evaluate(element => { const p = element.querySelector('.panel-audio-controls').getBoundingClientRect(); return { client: element.clientWidth, scroll: element.scrollWidth, controlsTop: p.top, controlsBottom: p.bottom, height: innerHeight } })
      assert(bounds.scroll <= bounds.client && bounds.controlsTop > 0 && bounds.controlsBottom < bounds.height, `Panel controls out of view ${width}`)
      await dialog.getByRole('button', { name: 'Play ECHO study', exact: true }).click(); await waitState('playing')
      await test.screenshot({ path: `artifacts/qa/phase4-panel-${width}.png` })
      await test.keyboard.press('Tab')
      assert(await dialog.evaluate(element => element.contains(document.activeElement)), 'Focus escaped audio dialog')
      await dialog.getByRole('button', { name: 'Stop ECHO study', exact: true }).click(); await released()
      await test.keyboard.press('Escape')
      results.mobile.push({ width, ...bounds })
    }
    await test.emulateMedia({ reducedMotion: 'reduce' })
    await test.getByRole('button', { name: 'View FORM study', exact: true }).click()
    const motion = await test.locator('.study-panel:not([hidden]) svg').getAttribute('data-frames')
    await test.getByRole('dialog').getByRole('button', { name: 'Play FORM study', exact: true }).click(); await waitState('playing'); await audible()
    assert(await test.locator('.study-panel:not([hidden]) svg').getAttribute('data-audio-reactive') === 'false', 'Reduced motion audio moves')
    // One repaint for state changes is allowed, ongoing rendering is not.
    const frozen = await test.locator('.study-panel:not([hidden]) svg').getAttribute('data-frames')
    await test.evaluate(async () => { for (let i = 0; i < 12; i++) await new Promise(requestAnimationFrame) })
    assert(frozen === await test.locator('.study-panel:not([hidden]) svg').getAttribute('data-frames'), 'Reduced motion keeps rendering')
    await test.keyboard.press('Escape')
    await test.getByRole('button', { name: 'Start a project', exact: true }).first().click()
    await released()
    assert((await snapshot()).reason === 'brief', 'Project brief did not stop audio')
    await test.keyboard.press('Escape')
    results.final = await snapshot()
    await test.evaluate(() => window.dispatchEvent(new PageTransitionEvent('pagehide', { persisted: false })))
    assert(await test.evaluate(() => window.__phaseContexts[0].state) === 'closed', 'Page teardown leaves context open')
    assert(results.errors.length === 0, results.errors.join('\n'))
    return results
  } finally { await context.close() }
}

